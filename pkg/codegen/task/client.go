var clientIdentifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
var acronymBoundary = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
var wordBoundary = regexp.MustCompile(`([a-z0-9])([A-Z])`)

func pythonMethod(name string) string {
	name = acronymBoundary.ReplaceAllString(name, `${1}_${2}`)
	return "run_" + strings.ToLower(wordBoundary.ReplaceAllString(name, `${1}_${2}`))
}

// GenerateClient generates a self-contained Python or Node.js task producer.
// It only needs the task spec and its local schema references, not a Go module.
func GenerateClient(workdir, language, taskDefPath, outPath string) error {
	if language != "python" && language != "nodejs" {
		return fmt.Errorf("task-client language must be python or nodejs, got %q", language)
	}
	if taskDefPath == "" || outPath == "" {
		return fmt.Errorf("task-client path and out are required")
	}
	ext := filepath.Ext(outPath)
	if (language == "python" && ext != ".py") || (language == "nodejs" && ext != ".js" && ext != ".cjs" && ext != ".mjs") {
		return fmt.Errorf("task-client out must end in .py for python or .js/.cjs/.mjs for nodejs")
	}
	input := taskDefPath
	if !filepath.IsAbs(input) {
		input = filepath.Join(workdir, input)
	}
	input, err := filepath.Abs(input)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	var data map[string]any
	if err := yaml.Unmarshal(raw, &data); err != nil {
		return err
	}
	if err := validateClientNames(data, language); err != nil {
		return err
	}
	types := newClientTypes(language)
	for _, raw := range data["tasks"].([]any) {
		name := utils.UpperFirst(raw.(map[string]any)["name"].(string)) + "Parameters"
		types.names[name] = 1
	}
	var functions []Function
	resetGlobalTypeNameCounter()
	err = process(data, func(f Function) error {
		functions = append(functions, f)
		return nil
	}, func(name string, params map[string]any) (paramSpec, error) {
		typ, err := types.render(input, name+"Value", params)
		if err != nil {
			return paramSpec{}, fmt.Errorf("%s: %w", name, err)
		}
		if typ != name {
			types.alias(name, typ)
		}
		return paramSpec{Type: name}, nil
	})
	if err != nil {
		return err
	}
	queries, err := clientQueries()
	if err != nil {
		return err
	}
	code, declarations := renderClient(language, ext == ".mjs", functions, types.definitions, queries)
	output := outPath
	if !filepath.IsAbs(output) {
		output = filepath.Join(workdir, output)
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	if err := os.WriteFile(output, []byte(code), 0644); err != nil {
		return err
	}
	if language == "nodejs" {
		declarationExt := ".d.ts"
		if ext == ".mjs" {
			declarationExt = ".d.mts"
		} else if ext == ".cjs" {
			declarationExt = ".d.cts"
		}
		return os.WriteFile(strings.TrimSuffix(output, ext)+declarationExt, []byte(declarations), 0644)
	}
	return nil
}

func validateClientNames(data map[string]any, language string) error {
	tasks, ok := data["tasks"].([]any)
	if !ok {
		return fmt.Errorf("tasks is not an array")
	}
	seen := map[string]bool{}
	for _, raw := range tasks {
		task, ok := raw.(map[string]any)
		if !ok {
			return fmt.Errorf("task must be a mapping")
		}
		name, _ := task["name"].(string)
		if !clientIdentifier.MatchString(name) {
			return fmt.Errorf("task name %q must be an identifier", name)
		}
		method := "run" + utils.UpperFirst(name)
		if language == "python" {
			method = pythonMethod(name)
		}
		if seen[method] {
			return fmt.Errorf("task name %q generates duplicate method %s", name, method)
		}
		seen[method] = true
	}
	return nil
}

func clientAttributes(f Function) map[string]any {
	attrs := map[string]any{}
	if f.Timeout != nil {
		attrs["timeout"] = *f.Timeout
	}
	if f.Cronjob != nil {
		attrs["cronjob"] = map[string]any{"cronExpression": f.Cronjob.CronExpression}
	}
	if f.RetryPolicy != nil {
		attrs["retryPolicy"] = map[string]any{"interval": f.RetryPolicy.Interval, "maxAttempts": f.RetryPolicy.MaxAttempts}
	}
	if f.ReleaseUniqueTagOnTerminal != nil {
		attrs["releaseUniqueTagOnTerminal"] = *f.ReleaseUniqueTagOnTerminal
	}
	if f.Labels != nil {
		attrs["labels"] = f.Labels
	}
	if f.Tags != nil {
		attrs["tags"] = f.Tags
	}
	if f.Priority != nil {
		attrs["priority"] = *f.Priority
	}
	return attrs
}

func renderClient(language string, esm bool, functions []Function, definitions []string, queries map[string]string) (string, string) {
	var code, declarations strings.Builder
	if language == "python" {
		code.WriteString("# Code generated by anclax; DO NOT EDIT.\n")
		code.WriteString(strings.Replace(pythonClientRuntime, "{{SQL}}", renderClientQueries(language, queries), 1))
		code.WriteString("\n\n")
		code.WriteString(strings.Join(definitions, "\n\n"))
		code.WriteString(`

class Client(TaskClient):
    """Typed task methods using an application-owned pool or connection.

    Inside a business transaction, construct Client(conn) with the same
    connection used for business SQL. Business writes and new tasks then commit
    or roll back together. The caller manages the transaction and connection.
    """

`)
		if len(functions) == 0 {
			code.WriteString("    pass\n")
		}
		for _, f := range functions {
			fmt.Fprintf(&code, "    async def %s(self, params: %s, *, options: TaskOptions | None = None) -> int:\n", pythonMethod(f.Name), f.ParameterType)
			if f.Description != "" {
				fmt.Fprintf(&code, "        %s\n", clientLiteral(f.Description, language))
			}
			fmt.Fprintf(&code, "        return await self.enqueue(%s, params, options=options, attributes=%s",
				clientLiteral(f.Name, language), clientLiteral(clientAttributes(f), language))
			if f.Delay != nil {
				delay, _ := time.ParseDuration(*f.Delay)
				fmt.Fprintf(&code, ", delay_seconds=%s", strconv.FormatFloat(delay.Seconds(), 'g', -1, 64))
			}
			code.WriteString(")\n\n")
		}
		return strings.TrimRight(code.String(), "\n") + "\n", ""
	}
	code.WriteString("// Code generated by anclax; DO NOT EDIT.\n")
	code.WriteString(strings.Replace(nodeClientRuntime, "{{SQL}}", renderClientQueries(language, queries), 1))
	const nodeClientDoc = `/**
 * Typed task methods using an application-owned pool or connection.
 * Inside a business transaction, construct new Client(conn) with the same
 * connection used for business SQL. Business writes and new tasks then commit
 * or roll back together. The caller manages the transaction and connection.
 */`
	code.WriteString("\n" + nodeClientDoc + "\nclass Client extends TaskClient {\n")
	declarations.WriteString("// Code generated by anclax; DO NOT EDIT.\n")
	declarations.WriteString(nodeClientDeclarations)
	declarations.WriteString("\n")
	declarations.WriteString(strings.Join(definitions, "\n\n"))
	declarations.WriteString("\n\n" + nodeClientDoc + "\nexport class Client extends TaskClient {\n")
	for _, f := range functions {
		method := "run" + utils.UpperFirst(f.Name)
		if f.Description != "" {
			for _, line := range strings.Split(strings.ReplaceAll(f.Description, "\r", ""), "\n") {
				fmt.Fprintf(&declarations, "  // %s\n", line)
			}
		}
		fmt.Fprintf(&declarations, "  %s(params: %s, options?: TaskOptions): Promise<number>;\n", method, f.ParameterType)
		defaults := map[string]any{"attributes": clientAttributes(f)}
		if f.Delay != nil {
			delay, _ := time.ParseDuration(*f.Delay)
			defaults["delayMs"] = float64(delay) / float64(time.Millisecond)
		}
		fmt.Fprintf(&code, "  async %s(params, options) {\n    return this.enqueue(%s, params, options, %s);\n  }\n",
			method, clientLiteral(f.Name, language), clientLiteral(defaults, language))
	}
	code.WriteString("}\n")
	if esm {
		code.WriteString("\nexport { Client, TaskClient };\n")
	} else {
		code.WriteString("\nexports.Client = Client;\nexports.TaskClient = TaskClient;\n")
	}
	declarations.WriteString("}\n")
	return code.String(), declarations.String()
}
